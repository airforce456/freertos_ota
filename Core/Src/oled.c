void OLED_WriteCmd(uint8_t cmd)
{
    MyI2C_Start();

    MyI2C_SendByte(OLED_ADDR<<1);

    if(MyI2C_ReciveAck())
    {
        MyI2C_Stop();
        return ;
    }
    MyI2C_SendByte(OLED_CMD);
    if(MyI2C_ReciveAck())
    {
        MyI2C_Stop();
        return ;
    }

    MyI2C_SendByte(cmd);
    if(MyI2C_ReciveAck())
    {
        MyI2C_Stop();
        return ;
    }
    MyI2C_Stop();

}

void OLED_WriteData(uint8_t data)
{
    MyI2C_Start();

    MyI2C_SendByte(OLED_ADDR<<1);

    if(MyI2C_ReciveAck())
    {
        MyI2C_Stop();
        return ;
    }
     MyI2C_SendByte(OLED_DATA);
    if(MyI2C_ReciveAck())
    {
        MyI2C_Stop();
        return ;
    }
    
    MyI2C_SendByte(data);
    if(MyI2C_ReciveAck())
    {
        MyI2C_Stop();
        return ;
    }
    MyI2C_Stop();
}


void OLED_WriteCmdBuf(const uint8_t *cmds,uint8_t len)
{
    MyI2C_Start();

    MyI2C_SendByte(OLED_ADDR<<1);

    if(MyI2C_ReciveAck())
    {
        MyI2C_Stop();
        return ;
    }
    MyI2C_SendByte(OLED_CMD);
    if(MyI2C_ReciveAck())
    {
        MyI2C_Stop();
        return ;
    }
    for(uint8_t i=0;i<len;i++)
    {
        MyI2C_SendByte(cmds[i]);
        if(MyI2C_ReciveAck())
        {
            MyI2C_Stop();
            return ;
        }

    }
    
    
    MyI2C_Stop();
}
